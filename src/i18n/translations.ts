export function getGradeLabel(grade: string, lang: Language): string {
  if (lang !== 'bn') return grade;
  if (grade === 'Pre-Primary') return 'প্রি-প্রাইমারি';
  const rangeMatch = grade.match(/^Grade\s+(\d+)\s*[–-]\s*(\d+)$/i);
  if (rangeMatch) {
    return `শ্রেণি ${toBnNum(rangeMatch[1])}–${toBnNum(rangeMatch[2])}`;
  }
  const match = grade.match(/^Grade\s+(\d+)$/i);
  if (match) {
    return `শ্রেণি ${toBnNum(match[1])}`;
  }
  return toBnNum(grade);
}

export function getAgeBandLabel(band: string, lang: Language): string {
  if (lang !== 'bn') return band;
  return toBnNum(
    band
      .replace(/years?/gi, 'বছর')
      .replace(/yrs?/gi, 'বছর')
      .replace(/\s+/g, ' ')
      .trim()
  );
}

