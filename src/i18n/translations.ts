const BN_DIGITS = ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯'];

export function toBnNum(val: number | string, lang?: Language): string {
  if (lang && lang !== 'bn') return String(val);
  return String(val).replace(/\d/g, (d) => BN_DIGITS[Number(d)]);
}

export function formatNum(val: number | string, lang: Language): string {
  return toBnNum(val, lang);
}

