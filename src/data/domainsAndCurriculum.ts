export function getDomainsForStudent(
  age = 11,
  grade?: string
): {
  primaryDomains: AgeOrganizedDomain[];
  allDomains: AgeOrganizedDomain[];
  stageLabel: string;
  stageLabelBn: string;
} {
  const gradeLevel = grade ? parseGradeLevel(grade) : age <= 5 ? 0 : age <= 7 ? 1 : age <= 10 ? 4 : 6;

  let primaryIds: string[];
  let stageKey: 'preprimary' | 'primary_early' | 'primary_upper' | null = null;
  let stageLabel = 'Middle & Secondary Mathematics Track';
  let stageLabelBn = 'মাধ্যমিক পর্যায়ের সম্পূর্ণ গণিত ডোমেইন';

  if (gradeLevel === 0 || age <= 5) {
    stageKey = 'preprimary';
    stageLabel = 'Pre-Primary Early Learners (Age 4–5 · NCTB)';
    stageLabelBn = 'প্রি-প্রাইমারি বয়স উপযোগী ডোমেইন (৪–৫ বছর · এনসিটিবি)';
    primaryIds = [
      'Number Sense',
      'Number Operations',
      'Geometry',
      'Measurement',
      'Pattern Recognition',
      'Spatial and Visual Reasoning',
    ];
  } else if (gradeLevel <= 2 || age <= 7) {
    stageKey = 'primary_early';
    stageLabel = `Primary Foundational Track (${grade || 'Grade 1–2'} · NCTB)`;
    stageLabelBn = `প্রাথমিক ভিত্তি পর্যায় (${gradeLevel === 1 ? '১ম শ্রেণি' : '২য় শ্রেণি'} · এনসিটিবি)`;
    primaryIds = [
      'Number Sense',
      'Number Operations',
      'Geometry',
      'Measurement',
      'Pattern Recognition',
      'Mathematical Reasoning',
      'Data Handling and Statistics',
      'Spatial and Visual Reasoning',
    ];
  } else if (gradeLevel <= 5 || age <= 10) {
    stageKey = 'primary_upper';
    stageLabel = `Upper Primary Track (${grade || 'Grade 3–5'} · NCTB)`;
    stageLabelBn = `প্রাথমিক উচ্চতর পর্যায় (${grade || '৩য়–৫ম শ্রেণি'} · এনসিটিবি)`;
    primaryIds = [
      'Number Sense',
      'Number Operations',
      'Fractions, Decimals and Percentages',
      'Geometry',
      'Measurement',
      'Pattern Recognition',
      'Data Handling and Statistics',
      'Mathematical Reasoning',
      'Spatial and Visual Reasoning',
      ...(gradeLevel >= 4 ? ['Algebraic Thinking'] : []),
    ];
  } else {
    primaryIds = [
      'Number Sense',
      'Number Operations',
      'Fractions, Decimals and Percentages',
      'Ratio and Proportion',
      'Algebraic Thinking',
      'Geometry',
      'Measurement',
      'Data Handling and Statistics',
      'Probability',
      'Pattern Recognition',
      'Spatial and Visual Reasoning',
      'Mathematical Reasoning',
    ];
  }

  const enriched: AgeOrganizedDomain[] = MATH_DOMAINS.map((d) => {
    const ov = stageKey ? EARLY_STAGE_OVERRIDES[stageKey]?.[d.id] : undefined;
    return {
      ...d,
      displayName: ov?.name || d.name,
      displayNameBn: ov?.nameBn || d.nameBn,
      displayDescription: ov?.desc || d.description,
      displayDescriptionBn: ov?.descBn || d.description,
      recommendedForAge: primaryIds.includes(d.id),
    };
  });

  // Sort recommended domains first in developmental order
  const sorted = [...enriched].sort((a, b) => {
    const idxA = primaryIds.indexOf(a.id);
    const idxB = primaryIds.indexOf(b.id);
    if (idxA !== -1 && idxB !== -1) return idxA - idxB;
    if (idxA !== -1) return -1;
    if (idxB !== -1) return 1;
    return 0;
  });

  return {
    primaryDomains: sorted.filter((d) => d.recommendedForAge),
    allDomains: sorted,
    stageLabel,
    stageLabelBn,
  };
}

