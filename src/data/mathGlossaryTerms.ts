export interface GlossaryTextSegment {
  type: 'text' | 'term';
  text: string;
  entry?: GlossaryTermEntry;
}

interface AliasEntry {
  alias: string;
  isLatin: boolean;
  entry: GlossaryTermEntry;
}

const ALL_ALIASES: AliasEntry[] = [];
const ALIAS_LOOKUP = new Map<string, GlossaryTermEntry>();

for (const entry of MATH_GLOSSARY_TERMS) {
  for (const a of entry.aliasesEn ?? [entry.termEn]) {
    const trimmed = a.trim();
    if (!trimmed) continue;
    ALL_ALIASES.push({ alias: trimmed, isLatin: true, entry });
    ALIAS_LOOKUP.set(trimmed.toLowerCase(), entry);
  }
  for (const b of entry.aliasesBn ?? [entry.termBn]) {
    const trimmed = b.trim();
    if (!trimmed) continue;
    ALL_ALIASES.push({ alias: trimmed, isLatin: false, entry });
    ALIAS_LOOKUP.set(trimmed, entry);
  }
}

// Longest aliases first so multi-word terms match before sub-words
ALL_ALIASES.sort((a, b) => b.alias.length - a.alias.length);

function escapeRegex(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

const LATIN_PATTERNS = ALL_ALIASES.filter((a) => a.isLatin).map((a) => escapeRegex(a.alias));
const BENGALI_PATTERNS = ALL_ALIASES.filter((a) => !a.isLatin).map((a) => escapeRegex(a.alias));

const COMBINED_REGEX =
  LATIN_PATTERNS.length > 0 && BENGALI_PATTERNS.length > 0
    ? new RegExp(
        `(?:\\b(${LATIN_PATTERNS.join('|')})\\b)|(?:(?<![\\u0980-\\u09FF])(${BENGALI_PATTERNS.join('|')})(?![\\u0980-\\u09FF]))`,
        'gi'
      )
    : null;

/**
 * Splits plain prose into non-term text and clickable recognized mathematical terms.
 * Safe against partial word matches (e.g., won't match "area" inside "linear").
 */
export function tokenizeTextWithGlossaryTerms(input: string): GlossaryTextSegment[] {
  if (!input || input.length < 2 || !COMBINED_REGEX) {
    return [{ type: 'text', text: input }];
  }

  const segments: GlossaryTextSegment[] = [];
  let lastIdx = 0;
  COMBINED_REGEX.lastIndex = 0;

  let match: RegExpExecArray | null;
  while ((match = COMBINED_REGEX.exec(input)) !== null) {
    const matchedText = match[0];
    if (!matchedText) break;

    const start = match.index;
    if (start > lastIdx) {
      segments.push({ type: 'text', text: input.slice(lastIdx, start) });
    }

    const entry =
      ALIAS_LOOKUP.get(matchedText.toLowerCase()) || ALIAS_LOOKUP.get(matchedText);

    if (entry) {
      segments.push({ type: 'term', text: matchedText, entry });
    } else {
      segments.push({ type: 'text', text: matchedText });
    }

    lastIdx = start + matchedText.length;
  }

  if (lastIdx < input.length) {
    segments.push({ type: 'text', text: input.slice(lastIdx) });
  }

  return segments.length > 0 ? segments : [{ type: 'text', text: input }];
}

export function getDisplayTerm(entry: GlossaryTermEntry, language: Language): string {
  return language === 'bn' ? entry.termBn : entry.termEn;
}
